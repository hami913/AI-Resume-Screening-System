def _group_detected_skills(skills: Sequence[str]) -> Dict[str, List[str]]:
    grouped: Dict[str, List[str]] = defaultdict(list)
    for raw_skill in skills:
        canonical = normalize_skill(raw_skill)
        grouped[category_for_skill(canonical)].append(display_skill(canonical if canonical else raw_skill))
    return {category: sorted(set(values)) for category, values in sorted(grouped.items())}


