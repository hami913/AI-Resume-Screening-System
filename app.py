    pdf.cell(92, 5, trailing, new_x="LMARGIN", new_y="NEXT", align="R")

    bar_y = y + 6
    pdf.set_fill_color(229, 234, 242)
    pdf.rect(15, bar_y, 180, 3, style="F")
