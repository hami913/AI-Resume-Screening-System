class ModernReportPDF(FPDF):
    def __init__(self):
        super().__init__()
        self.set_margins(15, 15, 15)
        self.set_auto_page_break(auto=True, margin=18)

    def header(self):
        # Top Accent Banner
        self.set_fill_color(30, 27, 75)  # Deep Indigo (#1E1B4B)
        self.rect(0, 0, 210, 12, style="F")
        self.set_fill_color(79, 70, 229)  # Accent Indigo (#4F46E5)
        self.rect(0, 12, 210, 2, style="F")

        # Running Header Text
        self.set_y(15)
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(148, 163, 184)  # Slate Muted
        self.cell(0, 5, "ENTERPRISE AI RESUME ANALYTICS REPORT", new_x="LMARGIN", new_y="NEXT", align="R")
        self.ln(2)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(148, 163, 184)
        
        # Divider Line
        self.set_draw_color(226, 232, 240)
        self.line(15, 282, 195, 282)

        # Left side: Confidentiality note; Right side: Page Numbering
        self.cell(100, 10, "Confidential - Generated by AI Career Assistant", align="L")
        self.cell(80, 10, f"Page {self.page_no()}", align="R")


def sanitize_pdf_text(text: str, max_word_len: int = 20) -> str:
    """Prepare text for safe rendering in FPDF's cell/multi_cell.
    Guards against FPDF's 'Not enough horizontal space' error by:
      1. Forcing a space after common punctuation.
      2. Breaking individual long tokens into space-joined chunks.
    """
    if not text:
        return ""

    text = str(text)
    text = re.sub(r'([,;:!?/])([^\s])', r'\1 \2', text)
    text = re.sub(r'\s+', ' ', text).strip()

    safe_tokens = []
    for word in text.split(' '):
        if len(word) <= max_word_len:
            safe_tokens.append(word)
            continue
        chunks = [word[i:i + max_word_len] for i in range(0, len(word), max_word_len)]
        safe_tokens.append(' '.join(chunks))

    return ' '.join(safe_tokens)


def safe_multi_cell(
    pdf,
    w: float,
    h: float,
    text: str,
    max_word_len: int = 20,
    min_effective_width_mm: float = 15.0,
    **kwargs,
) -> None:
    """Defensive wrapper around FPDF.multi_cell that prevents line-overflow crashes."""
    safe_text = sanitize_pdf_text(text, max_word_len=max_word_len)
    safe_text = safe_text.encode('latin-1', 'replace').decode('latin-1')

    if not safe_text:
        return

    effective_width = w if w > 0 else (pdf.w - pdf.r_margin - pdf.x)
    if effective_width < min_effective_width_mm:
        pdf.ln(h)
        pdf.set_x(pdf.l_margin)
        w = 0

    try:
        pdf.multi_cell(w, h, safe_text, **kwargs)
    except Exception:
        current_size = pdf.font_size_pt
        pdf.set_font_size(max(current_size - 2, 6))
        forced_break = ' '.join(safe_text[i:i + 8] for i in range(0, len(safe_text), 8))
        pdf.multi_cell(w, h, forced_break, **kwargs)
        pdf.set_font_size(current_size)


def draw_section_heading(pdf, title: str):
    """Draws a stylish modern section header with background pill."""
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_fill_color(241, 245, 249)  # Light Slate Tint
    pdf.set_text_color(30, 41, 59)     # Slate Dark Text
    pdf.cell(180, 8, f"  {title}", new_x="LMARGIN", new_y="NEXT", fill=True)
    pdf.ln(3)


def generate_pdf_report(predicted_category, confidence, ats_res, feature_dict, logo_path=None):
    """Generate a downloadable, high-aesthetic PDF report for a single resume analysis."""
    pdf = ModernReportPDF()
    pdf.add_page()

    # ----------------------------------------------------
    # BRAND HEADER & LOGO INTEGRATION
    # ----------------------------------------------------
    start_y = pdf.get_y()
    
    # Render Logo if provided and valid
    if logo_path and os.path.exists(logo_path):
        try:
            pdf.image(logo_path, x=15, y=start_y, w=20)
            text_x = 38
        except Exception:
            text_x = 15
    else:
        text_x = 15

    pdf.set_xy(text_x, start_y)
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(15, 23, 42)  # Charcoal
    pdf.cell(0, 8, "Resume Analysis & ATS Audit", new_x="LMARGIN", new_y="NEXT")

    pdf.set_x(text_x)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 116, 139)  # Slate Muted
    pdf.cell(0, 5, "Automated Diagnostic Profile & Candidate Metrics", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_y(max(pdf.get_y() + 4, start_y + 22))
    pdf.set_draw_color(226, 232, 240)
    pdf.line(15, pdf.get_y(), 195, pdf.get_y())
    pdf.ln(5)

    # ----------------------------------------------------
    # SECTION 1: CATEGORIZATION SUMMARY
    # ----------------------------------------------------
    draw_section_heading(pdf, "1. CAREER PREDICTION & CONFIDENCE")

    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(71, 85, 105)
    
    # Key-Value Info Cards
    pdf.cell(90, 6, "Predicted Job Category:", new_x="RIGHT", new_y="TOP")
    pdf.cell(90, 6, "Model Match Confidence:", new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(79, 70, 229)  # Primary Indigo Color
    safe_multi_cell(pdf, 90, 7, str(predicted_category))
    
    pdf.set_xy(105, pdf.get_y() - 7)
    pdf.set_text_color(16, 185, 129)  # Success Emerald Color
    safe_multi_cell(pdf, 90, 7, str(confidence))
    pdf.ln(4)

    # ----------------------------------------------------
    # SECTION 2: ATS MATCH & SKILL GAP ANALYSIS
    # ----------------------------------------------------
    draw_section_heading(pdf, "2. ATS MATCH & SKILL GAP ANALYSIS")

    ats_score = ats_res.get("ats_score", 0)
    
    # Score Summary Banner Card
    pdf.set_fill_color(248, 250, 252)
    pdf.rect(15, pdf.get_y(), 180, 16, style="F")
    
    pdf.set_xy(20, pdf.get_y() + 3)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(51, 65, 85)
    pdf.cell(50, 10, "Overall ATS Score:")

    pdf.set_font("Helvetica", "B", 16)
    if ats_score >= 75:
        pdf.set_text_color(16, 185, 129)  # Green
    elif ats_score >= 50:
        pdf.set_text_color(245, 158, 11)  # Amber
    else:
        pdf.set_text_color(244, 63, 94)   # Red
    
    pdf.cell(30, 10, f"{ats_score:.1f}%")

    matched_skills = ats_res.get('matched_skills', [])
    missing_skills = ats_res.get('missing_skills', [])
    jd_count = ats_res.get('jd_skill_count', len(matched_skills) + len(missing_skills))

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 10, f"Skill Match Coverage: {len(matched_skills)} / {jd_count} required skills", new_x="LMARGIN", new_y="NEXT", align="R")
    pdf.ln(6)

    # Matched Skills Box
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(16, 185, 129)
    pdf.cell(0, 6, "Matched Skills", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(51, 65, 85)
    matched_str = ", ".join(matched_skills) if matched_skills else "None Identified"
    safe_multi_cell(pdf, 180, 5, matched_str)
    pdf.ln(3)

    # Missing Skills Box (Gap Analysis)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(244, 63, 94)
    pdf.cell(0, 6, "Missing Skills (Gap Analysis)", new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(51, 65, 85)
    missing_str = ", ".join(missing_skills) if missing_skills else "No Critical Skill Gaps Found"
    safe_multi_cell(pdf, 180, 5, missing_str)
    pdf.ln(4)

    # ----------------------------------------------------
    # SECTION 3: RESUME METRICS GRID
    # ----------------------------------------------------
    draw_section_heading(pdf, "3. STRUCTURAL & TEXT METRICS")

    # Clean Styled Metrics Table
    metrics_data = [
        ("Total Word Count", str(feature_dict.get('word_count', 0))),
        ("Unique Words Detected", str(feature_dict.get('unique_word_count', 0))),
        ("Total Technical Skills Detected", str(feature_dict.get('skill_count', 0))),
        ("Email Contact Present", "Yes" if feature_dict.get('email_present') in [1, True] else "No"),
        ("Phone Contact Present", "Yes" if feature_dict.get('phone_present') in [1, True] else "No"),
    ]

    pdf.set_font("Helvetica", "", 9)
    fill = False
    for label, val in metrics_data:
        pdf.set_fill_color(248, 250, 252) if fill else pdf.set_fill_color(255, 255, 255)
        pdf.set_text_color(71, 85, 105)
        pdf.cell(120, 7, f"  {label}", border="B", fill=fill)
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(60, 7, val, border="B", new_x="LMARGIN", new_y="NEXT", align="C", fill=fill)
        pdf.set_font("Helvetica", "", 9)
        fill = not fill

    return bytes(pdf.output())


