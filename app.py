def _build_action_timeline(jd_result: Mapping[str, Any]) -> List[Tuple[str, str]]:
    critical = coerce_list(jd_result.get("critical_gaps"))
    important = coerce_list(jd_result.get("important_gaps"))
    unsupported = coerce_list(jd_result.get("unsupported_skills"))
    missing_context = coerce_list(jd_result.get("missing_context_terms"))
    failed_checks = [check for check in jd_result.get("structure_checks", []) if not check.get("passed")]

    steps: List[Tuple[str, str]] = []
    if critical:
        steps.append(("Validate critical requirements", "Learn or prove " + ", ".join(display_skill(skill) for skill in critical[:4]) + " before adding those keywords."))
    elif important:
        steps.append(("Close the highest-value skill gaps", "Prioritize " + ", ".join(display_skill(skill) for skill in important[:4]) + " based on real role relevance."))
    else:
        steps.append(("Protect the strong match", "Keep the matched skills relevant and remove unrelated content that dilutes the target profile."))

    if unsupported:
        steps.append(("Convert skill claims into evidence", "Add truthful project or experience bullets for " + ", ".join(display_skill(skill) for skill in unsupported[:4]) + "."))
    else:
        steps.append(("Sharpen achievement evidence", "Strengthen the best matched skills with ownership verbs, scale, metrics, and outcomes."))

    if missing_context:
        steps.append(("Align target-role language", "Naturally reflect relevant terms such as " + ", ".join(missing_context[:5]) + " where your real experience supports them."))
    else:
        steps.append(("Maintain contextual alignment", "Keep the resume wording specific to the role without copying the job description verbatim."))

    if failed_checks:
        steps.append(("Repair resume structure", "Fix the highest-impact layout and evidence checks before exporting the final tailored version."))
    else:
        steps.append(("Run final recruiter review", "Check readability, truthfulness, spelling, dates, and consistent formatting before applying."))
    return steps


