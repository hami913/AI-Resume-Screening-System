def section_tag(label):
    return f'<div class="section-tag">{label}</div>'


def pills_html(items, variant="slate"):
    if not items:
        return ""
    return "".join(
        f'<span class="pill pill-{variant}">{item}</span>' for item in items
    )


def score_variant(score):
    try:
        score = float(score)
    except (TypeError, ValueError):
        score = 0.0

    if score >= 75:
        return "#10B981", "teal"
    if score >= 50:
        return "#F59E0B", "amber"
    return "#F43F5E", "rust"


def gauge_html(label, score):
    try:
        score = float(score)
    except (TypeError, ValueError):
        score = 0.0

    score = max(0.0, min(100.0, score))
    color, _ = score_variant(score)

    return f"""<div class="gauge-wrap">
        <div class="gauge" style="background: conic-gradient({color} {score}%, rgba(255,255,255,0.08) {score}%);">
            <div class="gauge-inner">
                <span class="gauge-value">{score:.0f}</span>
                <span class="gauge-suffix">%</span>
            </div>
        </div>
        <div class="gauge-label">{label}</div>
    </div>"""


