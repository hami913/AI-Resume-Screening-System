def sanitize_pdf_text(text: Any, max_word_len: int = 24) -> str:
    """Prepare arbitrary model/user text for safe rendering with core PDF fonts."""
    if text is None:
        return ""

    value = str(text)
    value = value.replace("\u2022", "-").replace("\u2014", "-").replace("\u2013", "-")
    value = re.sub(r"([,;:!?/])([^\s])", r"\1 \2", value)
    value = re.sub(r"\s+", " ", value).strip()

    safe_tokens: List[str] = []
    for word in value.split(" "):
        if len(word) <= max_word_len:
            safe_tokens.append(word)
            continue
        safe_tokens.extend(word[i : i + max_word_len] for i in range(0, len(word), max_word_len))

    return " ".join(safe_tokens).encode("latin-1", "replace").decode("latin-1")


def safe_multi_cell(
    pdf: FPDF,
    width: float,
    height: float,
    text: Any,
    max_word_len: int = 24,
    min_effective_width_mm: float = 15.0,
    **kwargs: Any,
) -> None:
    safe_text = sanitize_pdf_text(text, max_word_len=max_word_len)
    if not safe_text:
        return

    effective_width = width if width > 0 else (pdf.w - pdf.r_margin - pdf.x)
    if effective_width < min_effective_width_mm:
        pdf.ln(height)
        pdf.set_x(pdf.l_margin)
        width = 0

    try:
        pdf.multi_cell(width, height, safe_text, **kwargs)
    except Exception:
        current_size = pdf.font_size_pt
        pdf.set_font_size(max(current_size - 2, 6))
        forced = " ".join(safe_text[i : i + 10] for i in range(0, len(safe_text), 10))
        pdf.multi_cell(width, height, forced, **kwargs)
        pdf.set_font_size(current_size)


def ensure_pdf_space(pdf: FPDF, required_height: float = 30.0) -> None:
    if pdf.get_y() + required_height > pdf.h - pdf.b_margin:
        pdf.add_page()


