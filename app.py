def clamp(value: float, minimum: float = 0.0, maximum: float = 100.0) -> float:
    return max(minimum, min(maximum, value))


def safe_float(value: Any, default: float = 0.0) -> float:
    if value is None:
        return default
    try:
        if isinstance(value, str):
            value = value.strip().replace("%", "")
        return float(value)
    except (TypeError, ValueError):
        return default


def to_percent(value: Any) -> Optional[float]:
    """Normalize probabilities expressed as 0-1, 0-100, or strings with %."""
    if value is None or value == "":
        return None
    number = safe_float(value, default=math.nan)
    if math.isnan(number):
        return None
    if 0.0 <= number <= 1.0:
        number *= 100.0
    return round(clamp(number), 1)


def coerce_list(value: Any) -> List[str]:
    if value is None:
        return []
    if isinstance(value, str):
        chunks = re.split(r"[,;\n|]", value)
        return [chunk.strip() for chunk in chunks if chunk.strip()]
    if isinstance(value, (list, tuple, set)):
        return [str(item).strip() for item in value if str(item).strip()]
    return [str(value).strip()] if str(value).strip() else []


def file_signature(uploaded_file: Any) -> Optional[str]:
    if uploaded_file is None:
        return None
    try:
        payload = uploaded_file.getvalue()
    except Exception:
        try:
            payload = uploaded_file.getbuffer().tobytes()
        except Exception:
            return None
    return hashlib.sha256(payload).hexdigest()


def text_signature(text: str) -> str:
    return hashlib.sha256((text or "").strip().encode("utf-8", errors="ignore")).hexdigest()


def truncate_text(text: Any, limit: int) -> str:
    clean = re.sub(r"\s+", " ", str(text or "")).strip()
    if len(clean) <= limit:
        return clean
    return clean[: max(0, limit - 1)].rstrip() + "\u2026"


def safe_filename(value: str, fallback: str = "resume") -> str:
    base = os.path.splitext(value or "")[0]
    base = re.sub(r"[^A-Za-z0-9_-]+", "_", base).strip("_")
    return base[:70] or fallback


