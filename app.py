NEUTRAL_HEADING_PATTERN = re.compile(r"\b(responsibilities|what you will do|what you'll do|duties|role overview|about the role|day to day)\b", re.IGNORECASE)

ROLE_TITLE_PATTERN = re.compile(
    r"\b(engineer|developer|scientist|analyst|architect|manager|specialist|consultant|designer|"
    r"administrator|lead|director|coordinator|officer|researcher|intern|associate|executive)\b",
    re.IGNORECASE,
)
TITLE_NOISE = {
    "about us", "about the company", "job description", "description", "overview",
    "responsibilities", "requirements", "qualifications", "who we are", "the role",
}

SECTION_HEADING_ALIASES: Dict[str, Set[str]] = {
    "summary": {"summary", "professional summary", "profile", "professional profile", "career objective", "objective", "about me"},
    "experience": {"experience", "work experience", "professional experience", "employment", "employment history", "career history"},
    "education": {"education", "academic background", "academic qualifications", "qualifications"},
    "skills": {"skills", "technical skills", "core competencies", "competencies", "technologies", "technology stack", "tech stack"},
    "projects": {"projects", "selected projects", "personal projects", "academic projects", "project experience", "portfolio"},
    "certifications": {"certifications", "certificates", "licenses", "licences", "professional development", "training and certifications"},
}


def normalize_skill(skill: str) -> str:
    normalized = normalize_match_text(skill)
    if normalized in ALIAS_TO_CANONICAL:
        return ALIAS_TO_CANONICAL[normalized]

    # Reasonable singular/plural normalization without turning generic JD words into skills.
    candidates = [normalized]
    if normalized.endswith("ies") and len(normalized) > 4:
        candidates.append(normalized[:-3] + "y")
    if normalized.endswith("s") and len(normalized) > 4 and not normalized.endswith("ss"):
        candidates.append(normalized[:-1])
    for candidate in candidates:
        if candidate in ALIAS_TO_CANONICAL:
            return ALIAS_TO_CANONICAL[candidate]
    return normalized


def display_skill(skill: str) -> str:
    canonical = normalize_skill(skill)
    meta = SKILL_CATALOG.get(canonical)
    if meta:
        return str(meta["label"])
    special = {
        "api": "API",
        "apis": "APIs",
        "ai": "AI",
        "ml": "ML",
        "sql": "SQL",
        "aws": "AWS",
        "gcp": "GCP",
        "nlp": "NLP",
        "llm": "LLM",
        "rag": "RAG",
        "html": "HTML",
        "css": "CSS",
    }
    return special.get(canonical, canonical.title())


def category_for_skill(skill: str) -> str:
    canonical = normalize_skill(skill)
    return str(SKILL_CATALOG.get(canonical, {}).get("category", "Other"))


def contains_skill(text: str, skill: str) -> bool:
    """Backward-compatible skill test using canonical aliases and flexible separators."""
    canonical = normalize_skill(skill)
    normalized_text = normalize_match_text(text)
    patterns = ALIAS_PATTERNS.get(canonical)
    if patterns:
        return any(pattern.search(normalized_text) for pattern in patterns)
    return bool(_alias_pattern(canonical).search(normalized_text))


def _skill_context_is_valid(canonical: str, original_text: str) -> bool:
    """Filter aliases that are ordinary English words unless technical context is visible."""
    text = str(original_text or "")
    lower = text.casefold()

    if canonical == "excel":
        return bool(
            re.search(r"\b(?:microsoft|ms)\s+excel\b", text, re.IGNORECASE)
            or re.search(r"\bExcel\b", text)
            or re.search(r"\b(spreadsheet|workbook|pivot table|vlookup|xlookup|excel formula)\b", lower)
        )
    if canonical == "react":
        return bool(
            re.search(r"\bReact(?:\.js|JS)?\b", text)
            or re.search(r"\breact(?:js|\.js)\b", lower)
            or ("react" in lower and re.search(r"\b(frontend|front end|javascript|typescript|jsx|web app)\b", lower))
        )
    if canonical == "spark":
        return bool(
            re.search(r"\b(?:Apache\s+Spark|PySpark|Spark)\b", text)
            or ("spark" in lower and re.search(r"\b(big data|distributed|data engineering|hadoop)\b", lower))
        )
    if canonical == "flutter":
        return bool(
            re.search(r"\bFlutter\b", text)
            or ("flutter" in lower and re.search(r"\b(dart|mobile app|android|ios)\b", lower))
        )
    if canonical == "dart":
        return bool(
            re.search(r"\bDart\b", text)
            or ("dart" in lower and re.search(r"\b(flutter|mobile app|android|ios)\b", lower))
        )
    if canonical == "flask":
        return bool(
            re.search(r"\bFlask\b", text)
            or ("flask" in lower and re.search(r"\b(python|api|backend|web framework)\b", lower))
        )
    if canonical == "lime":
        return bool(re.search(r"\bLIME\b", text) or re.search(r"\b(model interpretability|explainable ai|xai)\b", lower))
    if canonical == "rag":
        return bool(re.search(r"\bRAG\b", text) or "retrieval augmented generation" in normalize_match_text(text))
    return True


def extract_skills_from_text(text: str) -> Set[str]:
    normalized_text = normalize_match_text(text)
    found: Set[str] = set()
    for canonical, patterns in ALIAS_PATTERNS.items():
        if any(pattern.search(normalized_text) for pattern in patterns) and _skill_context_is_valid(canonical, text):
            found.add(canonical)

    # Avoid double-counting a broad concept when a more specific phrase is the same mention.
    if "generative ai" in found:
        found.discard("artificial intelligence")
    return found


def _priority_rank(level: str) -> int:
    return {"optional": 1, "important": 2, "critical": 3}.get(level, 0)


def extract_priority_map(jd_text: str) -> Dict[str, str]:
    """Classify each JD skill using nearby required/preferred language and heading context."""
    priority_map: Dict[str, str] = {}
    current_context = "important"

    raw_lines = [line.strip(" \t-:\u2022") for line in str(jd_text or "").splitlines()]
    for raw_line in raw_lines:
        if not raw_line:
            continue
        lower = raw_line.casefold()

        # Section headings influence following bullets but do not force the whole document.
        if len(raw_line) <= 80 and REQUIRED_HEADING_PATTERN.search(lower) and not re.search(r"\bnot required\b", lower):
            current_context = "critical"
        elif len(raw_line) <= 80 and OPTIONAL_HEADING_PATTERN.search(lower):
            current_context = "optional"
        elif len(raw_line) <= 80 and NEUTRAL_HEADING_PATTERN.search(lower):
            current_context = "important"

        line_level = current_context
        if OPTIONAL_PATTERN.search(lower):
            line_level = "optional"
        elif CRITICAL_PATTERN.search(lower) and not re.search(r"\bnot required\b", lower):
            line_level = "critical"

        for skill in extract_skills_from_text(raw_line):
            existing = priority_map.get(skill)
            if existing is None or _priority_rank(line_level) > _priority_rank(existing):
                priority_map[skill] = line_level

    # Sentence-level pass catches priorities in prose paragraphs.
    for segment in re.split(r"(?<=[.!?])\s+|[\u2022]", str(jd_text or "")):
        segment = segment.strip()
        if not segment:
            continue
        lower = segment.casefold()
        if OPTIONAL_PATTERN.search(lower):
            level = "optional"
        elif CRITICAL_PATTERN.search(lower) and not re.search(r"\bnot required\b", lower):
            level = "critical"
        else:
            continue
        for skill in extract_skills_from_text(segment):
            existing = priority_map.get(skill)
            if existing is None or _priority_rank(level) > _priority_rank(existing):
                priority_map[skill] = level

    return priority_map


def _canonical_context_text(text: str) -> str:
    normalized = normalize_match_text(text)

    # Replace skill aliases with a single canonical phrase token. Long aliases are replaced first.
    alias_pairs = sorted(ALIAS_TO_CANONICAL.items(), key=lambda item: len(item[0]), reverse=True)
    for alias, canonical in alias_pairs:
        token = canonical.replace(" ", "_").replace("/", "_").replace("-", "_")
        normalized = _alias_pattern(alias).sub(f" {token} ", normalized)

    role_phrases = {
        "software engineering": "software_engineer",
        "software engineer": "software_engineer",
        "data scientist": "data_science",
        "data science": "data_science",
        "data analyst": "data_analysis",
        "data analytics": "data_analysis",
        "machine learning engineer": "machine_learning_engineer",
        "business analyst": "business_analysis",
        "project manager": "project_management",
        "product manager": "product_management",
    }
    for phrase, token in sorted(role_phrases.items(), key=lambda item: len(item[0]), reverse=True):
        normalized = _alias_pattern(phrase).sub(f" {token} ", normalized)

    return re.sub(r"\s+", " ", normalized).strip()


def _stem_context_token(token: str) -> str:
    token = token.strip("._+#-").casefold()
    if not token:
        return ""
    if token in CONTEXT_EQUIVALENTS:
        return CONTEXT_EQUIVALENTS[token]
    if "_" in token:
        return token
    if token.endswith("ies") and len(token) > 5:
        return token[:-3] + "y"
    if token.endswith("s") and len(token) > 5 and not token.endswith("ss"):
        token = token[:-1]
    return CONTEXT_EQUIVALENTS.get(token, token)


def _context_term_counter(text: str) -> Counter[str]:
    normalized = _canonical_context_text(text)
    raw_tokens = re.findall(r"\b[a-z][a-z0-9+#._-]{2,}\b", normalized)
    counter: Counter[str] = Counter()
    for raw in raw_tokens:
        token = _stem_context_token(raw)
        if not token or token in STOPWORDS or token.isdigit():
            continue
        counter[token] += 1
    return counter


def _display_context_term(term: str) -> str:
    candidate = term.replace("_", " ")
    normalized_candidate = normalize_skill(candidate)
    if normalized_candidate in SKILL_CATALOG:
        return display_skill(normalized_candidate)
    return candidate.title()


def compute_context_analysis(jd_text: str, candidate_text: str) -> Dict[str, Any]:
    """Lightweight semantic-ish context comparison without embeddings or new dependencies."""
    jd_counter = _context_term_counter(jd_text)
    resume_counter = _context_term_counter(candidate_text)
    if not jd_counter:
        return {"score": 0.0, "matched_terms": [], "missing_terms": [], "term_count": 0}

    weighted_terms: List[Tuple[str, float]] = []
    for term, frequency in jd_counter.items():
        weight = 1.0 + min(math.log1p(frequency), 1.4)
        if "_" in term:
            weight *= 1.45
        elif term in PROFESSIONAL_TERMS:
            weight *= 1.2
        weighted_terms.append((term, weight))

    # Long employer descriptions often add noise. Focus on the highest-signal 90 terms.
    weighted_terms.sort(key=lambda item: (item[1], len(item[0])), reverse=True)
    weighted_terms = weighted_terms[:90]

    total_weight = sum(weight for _, weight in weighted_terms)
    matched_weight = sum(weight for term, weight in weighted_terms if term in resume_counter)
    score = round(100.0 * matched_weight / total_weight, 1) if total_weight else 0.0

    matched = [_display_context_term(term) for term, _ in weighted_terms if term in resume_counter]
    missing = [_display_context_term(term) for term, _ in weighted_terms if term not in resume_counter]
    return {
        "score": score,
        "matched_terms": list(dict.fromkeys(matched))[:20],
        "missing_terms": list(dict.fromkeys(missing))[:20],
        "term_count": len(weighted_terms),
    }


def compute_context_score(jd_text: str, candidate_text: str) -> float:
    """Backward-compatible wrapper retained for existing callers."""
    return safe_float(compute_context_analysis(jd_text, candidate_text).get("score"))


def _feature_flag(features: Mapping[str, Any], keys: Iterable[str]) -> Optional[bool]:
    for key in keys:
        if key not in features:
            continue
        value = features.get(key)
        if isinstance(value, str):
            lowered = value.strip().casefold()
            if lowered in {"yes", "true", "1", "present"}:
                return True
            if lowered in {"no", "false", "0", "missing"}:
                return False
        return bool(value)
    return None


def _normalize_heading_candidate(value: str) -> str:
    candidate = normalize_match_text(value)
    candidate = re.sub(r"[^a-z ]+", " ", candidate)
    return re.sub(r"\s+", " ", candidate).strip()


def _line_contains_section_heading(raw_line: str, aliases: Set[str]) -> bool:
    clean_line = re.sub(r"\s+", " ", raw_line).strip(" \u2022\t")
    if not clean_line or len(clean_line) > 100:
        return False

    # Exact standalone heading or a heading before a common separator.
    first_segment = re.split(r"[:|]", clean_line, maxsplit=1)[0].strip(" -")
    normalized_full = _normalize_heading_candidate(clean_line)
    normalized_first = _normalize_heading_candidate(first_segment)
    if normalized_full in aliases or normalized_first in aliases:
        return True

    # Some PDF extractors collapse an all-caps heading and its first content line.
    for alias in sorted(aliases, key=len, reverse=True):
        if normalized_full.startswith(alias + " "):
            raw_prefix = clean_line[: len(alias) + 3]
            if raw_prefix.upper() == raw_prefix and any(char.isalpha() for char in raw_prefix):
                return True
    return False


def _section_presence(text: str) -> Dict[str, bool]:
    raw_lines = [line for line in str(text or "").splitlines() if line.strip()]
    presence: Dict[str, bool] = {}
    for section, aliases in SECTION_HEADING_ALIASES.items():
        presence[section] = any(_line_contains_section_heading(line, aliases) for line in raw_lines)
    return presence


def compute_resume_structure_score(resume_result: Mapping[str, Any]) -> Dict[str, Any]:
    """Calculate a real, explainable structure score instead of using a fixed constant."""
    candidate_text = get_resume_text(resume_result)
    features = get_resume_features(resume_result)
    sections = _section_presence(candidate_text)

    email_present = _feature_flag(features, ["email_present", "has_email", "email"])
    if email_present is None:
        email_present = bool(re.search(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", candidate_text, re.IGNORECASE))

    phone_present = _feature_flag(features, ["phone_present", "has_phone", "phone"])
    if phone_present is None:
        phone_present = bool(re.search(r"(?:\+?\d[\d\s().-]{7,}\d)", candidate_text))

    word_count = int(safe_float(features.get("word_count"), default=len(re.findall(r"\b\w+\b", candidate_text))))
    action_count = len(ACTION_VERBS_PATTERN.findall(candidate_text))
    metric_count = len(METRIC_PATTERN.findall(candidate_text))
    bullet_count = len(re.findall(r"(?m)^\s*(?:[-\u2022\u25aa\u25e6]|\d+[.)])\s+", candidate_text))

    checks: List[Dict[str, Any]] = []

    def add_check(label: str, passed: bool, points: float, partial: float = 0.0, detail: str = "") -> None:
        earned = points if passed else partial
        checks.append({
            "label": label,
            "passed": passed,
            "points": float(points),
            "earned": float(earned),
            "detail": detail,
        })

    add_check("Professional email address is present", bool(email_present), 6)
    add_check("Phone contact is present", bool(phone_present), 6)
    add_check("Experience section is clearly identified", sections.get("experience", False), 18)
    add_check("Education section is clearly identified", sections.get("education", False), 10)
    add_check("Skills section is clearly identified", sections.get("skills", False), 14)
    add_check("Summary or profile section is present", sections.get("summary", False), 8)
    add_check("Projects section strengthens evidence", sections.get("projects", False), 6)
    add_check("Certifications or professional development are shown", sections.get("certifications", False), 4)
    add_check(
        "Action verbs demonstrate ownership",
        action_count >= 4,
        8,
        partial=4 if action_count >= 2 else 0,
        detail=f"{action_count} action-oriented verb(s) detected",
    )
    add_check(
        "Achievements include measurable impact",
        metric_count >= 2,
        8,
        partial=4 if metric_count == 1 else 0,
        detail=f"{metric_count} measurable result signal(s) detected",
    )
    add_check(
        "Resume uses scannable bullet-style evidence",
        bullet_count >= 4,
        4,
        partial=2 if bullet_count >= 2 else 0,
        detail=f"{bullet_count} bullet line(s) detected",
    )
    optimal_length = 250 <= word_count <= 950
    partial_length = 4 if 150 <= word_count < 250 or 950 < word_count <= 1_200 else 0
    add_check(
        "Resume length is within a readable ATS range",
        optimal_length,
        8,
        partial=partial_length,
        detail=f"{word_count} words detected",
    )

    score = round(clamp(sum(item["earned"] for item in checks)), 1)
    return {
        "score": score,
        "checks": checks,
        "sections": sections,
        "contact_checks": {"email": bool(email_present), "phone": bool(phone_present)},
        "word_count": word_count,
        "action_verb_count": action_count,
        "metric_count": metric_count,
        "bullet_count": bullet_count,
    }


def compute_experience_relevance(candidate_text: str, matched_skills: Sequence[str]) -> Dict[str, Any]:
    """Measure whether matched skills are supported by action/project evidence, not merely listed."""
    canonical_skills = [normalize_skill(skill) for skill in matched_skills]
    if not canonical_skills:
        return {"score": 0.0, "evidence": [], "evidence_skills": [], "unsupported_skills": []}

    sentences = [
        re.sub(r"\s+", " ", segment).strip()
        for segment in re.split(r"(?<=[.!?])\s+|[\n\u2022]", candidate_text or "")
        if re.sub(r"\s+", " ", segment).strip()
    ]

    evidence_rows: List[Dict[str, Any]] = []
    for skill in canonical_skills:
        best_score = 0.0
        best_sentence = ""
        for sentence in sentences:
            if not contains_skill(sentence, skill):
                continue
            has_action = bool(ACTION_VERBS_PATTERN.search(sentence))
            has_metric = bool(METRIC_PATTERN.search(sentence))
            if has_action and has_metric:
                sentence_score = 100.0
            elif has_action:
                sentence_score = 82.0
            elif has_metric:
                sentence_score = 68.0
            else:
                sentence_score = 48.0
            if sentence_score > best_score:
                best_score = sentence_score
                best_sentence = truncate_text(sentence, 210)

        evidence_rows.append({
            "skill": skill,
            "score": best_score,
            "evidence": best_sentence,
            "supported": best_score >= 68.0,
        })

    score = round(sum(row["score"] for row in evidence_rows) / len(evidence_rows), 1)
    evidence_skills = [row["skill"] for row in evidence_rows if row["supported"]]
    unsupported = [row["skill"] for row in evidence_rows if not row["supported"]]
    return {
        "score": score,
        "evidence": evidence_rows,
        "evidence_skills": evidence_skills,
        "unsupported_skills": unsupported,
    }


def guess_target_title(job_description: str) -> Optional[str]:
    text = str(job_description or "").strip()
    if not text:
        return None

    explicit = re.search(
        r"(?im)^\s*(?:job\s*title|position|role)\s*[:\-]\s*(.{3,90})$",
        text,
    )
    if explicit:
        return explicit.group(1).strip(" -:\u2022\t")

    candidates: List[str] = []
    for line in text.splitlines()[:14]:
        clean = re.sub(r"\s+", " ", line).strip(" -:\u2022\t")
        if not (3 <= len(clean) <= 90):
            continue
        if clean.casefold() in TITLE_NOISE:
            continue
        if ROLE_TITLE_PATTERN.search(clean):
            candidates.append(clean)

    if candidates:
        candidates.sort(key=lambda value: (len(value.split()) > 10, len(value)))
        return candidates[0]

    for line in text.splitlines()[:8]:
        clean = re.sub(r"\s+", " ", line).strip(" -:\u2022\t")
        if 3 <= len(clean) <= 70 and clean.casefold() not in TITLE_NOISE:
            return clean
    return None


def summarize_target_job(job_description: str, target_title: Optional[str], jd_skills: Sequence[str]) -> str:
    lines = [re.sub(r"\s+", " ", line).strip(" -:\u2022\t") for line in str(job_description or "").splitlines()]
    meaningful = [line for line in lines if len(line) >= 20 and line.casefold() not in TITLE_NOISE]
    summary_parts: List[str] = []
    if target_title:
        summary_parts.append(f"Target role: {target_title}.")
    if jd_skills:
        summary_parts.append("Key detected requirements: " + ", ".join(display_skill(skill) for skill in jd_skills[:12]) + ".")
    if meaningful:
        summary_parts.append(truncate_text(" ".join(meaningful[:3]), 520))
    return " ".join(summary_parts) or truncate_text(job_description, 600)


def recommendation_blueprint(skill: str) -> Tuple[str, str]:
    category = category_for_skill(skill)
    label = display_skill(skill)
    if category == "Cloud & DevOps":
        return (
            f"Show the actual {label} service, environment, deployment, or infrastructure task you used and quantify reliability, speed, cost, or scale where possible.",
            "Experience, Projects, Certifications, or a dedicated Technical Skills section.",
        )
    if category == "AI & Data":
        return (
            f"Demonstrate {label} through a real model, analysis, experiment, dataset, evaluation metric, or production workflow rather than listing it alone.",
            "Projects or Experience, supported by tools, methods, and measurable outcomes.",
        )
    if category == "Programming":
        return (
            f"Reference a real implementation built with {label}, including the problem solved, your contribution, and a verifiable result.",
            "Experience, Projects, GitHub/portfolio link, or Technical Skills.",
        )
    if category == "Web & APIs":
        return (
            f"Describe a real application, endpoint, integration, or interface delivered with {label}; include scale, users, latency, reliability, or business impact when truthful.",
            "Projects or Experience, ideally inside an achievement-focused bullet.",
        )
    if category == "Data & Databases":
        return (
            f"Show how you used {label} for querying, modeling, pipelines, data quality, performance, or analytics and add a concrete outcome if available.",
            "Experience, Projects, or a Data/Technology stack line.",
        )
    if category == "BI & Delivery":
        return (
            f"Connect {label} to a real dashboard, decision, delivery process, stakeholder outcome, or project result instead of adding a standalone keyword.",
            "Experience, Projects, or a concise Core Competencies section.",
        )
    return (
        f"Add {label} only after you can support it with a real task, project, certification, or measurable result.",
        "The most relevant Experience, Projects, Skills, or Certifications section.",
    )


def build_priority_recommendations(
    critical_gaps: Sequence[str],
    important_gaps: Sequence[str],
    optional_gaps: Optional[Sequence[str]] = None,
) -> List[Dict[str, str]]:
    recommendations: List[Dict[str, str]] = []
    ordered: List[Tuple[str, str]] = []
    ordered.extend((skill, "critical") for skill in critical_gaps)
    ordered.extend((skill, "important") for skill in important_gaps)
    ordered.extend((skill, "optional") for skill in (optional_gaps or []))

    for skill, priority in ordered[:7]:
        label = display_skill(skill)
        how, where = recommendation_blueprint(skill)
        if priority == "critical":
            why = f"The target role presents {label} as a required or essential capability, but the resume does not currently show it."
        elif priority == "important":
            why = f"{label} appears relevant to the target role and could materially improve job-fit evidence."
        else:
            why = f"{label} is framed as preferred or nice-to-have; it can strengthen the application after core gaps are addressed."
        recommendations.append({
            "skill": label,
            "priority": priority,
            "why": why,
            "how": "Only add it if you genuinely have the experience. " + how,
            "where": where,
        })
    return recommendations


def _failed_structure_recommendations(structure_checks: Sequence[Mapping[str, Any]]) -> List[str]:
    recs: List[str] = []
    for check in structure_checks:
        if check.get("passed"):
            continue
        label = str(check.get("label", ""))
        if "email" in label.casefold() or "phone" in label.casefold():
            recs.append("Place clear, professional contact details in the resume header so an ATS and recruiter can find them immediately.")
        elif "experience section" in label.casefold():
            recs.append("Use a clearly labeled Experience section with company, role, dates, and achievement-focused bullets.")
        elif "skills section" in label.casefold():
            recs.append("Add a concise Skills section grouped by relevant technologies; avoid keyword stuffing.")
        elif "measurable" in label.casefold():
            recs.append("Add truthful metrics to strong achievements, such as time saved, accuracy gained, revenue influenced, users served, or scale handled.")
        elif "action verbs" in label.casefold():
            recs.append("Start more bullets with clear ownership verbs such as built, led, deployed, improved, or automated.")
        elif "length" in label.casefold():
            recs.append("Tighten the resume to a recruiter-friendly length while preserving the most relevant evidence for the target role.")
        elif "summary" in label.casefold():
            recs.append("Add a short role-aligned summary that states your specialty, strongest evidence, and target direction.")
        elif "projects" in label.casefold():
            recs.append("Add a Projects section when projects are your strongest proof of job-relevant skills.")
        if len(recs) >= 4:
            break
    return list(dict.fromkeys(recs))


def build_fit_summary(ats_result: Mapping[str, Any]) -> str:
    score = safe_float(ats_result.get("ats_score"))
    label, _ = score_status(score)
    components = {
        "skill coverage": safe_float(ats_result.get("skill_coverage")),
        "keyword context": safe_float(ats_result.get("uniqueness_score")),
        "resume structure": safe_float(ats_result.get("section_score")),
        "experience evidence": safe_float(ats_result.get("experience_score")),
    }
    strongest = max(components, key=components.get)
    weakest = min(components, key=components.get)
    missing_count = len(coerce_list(ats_result.get("missing_skills")))
    return (
        f"{label}: the strongest signal is {strongest} ({components[strongest]:.0f}%), while "
        f"{weakest} ({components[weakest]:.0f}%) is the main constraint. "
        f"{missing_count} target skill gap(s) require review; add only evidence you can truthfully support."
    )


def compute_jd_match(resume_result: Dict[str, Any], job_description: str) -> Dict[str, Any]:
    """Target-job ATS engine with realistic, explainable 55/20/10/15 weighting."""
    if not job_description or not job_description.strip():
        return {}
    if not isinstance(resume_result, Mapping):
        return {}

    jd_text = str(job_description)
    candidate_text = get_resume_text(resume_result)

    jd_skills = extract_skills_from_text(jd_text)
    candidate_skills: Set[str] = set()
    for raw_skill in get_detected_skills(resume_result):
        normalized = normalize_skill(raw_skill)
        if normalized in SKILL_CATALOG:
            candidate_skills.add(normalized)
    candidate_skills.update(extract_skills_from_text(candidate_text))

    matched_skills = sorted(jd_skills.intersection(candidate_skills), key=display_skill)
    missing_skills = sorted(jd_skills.difference(candidate_skills), key=display_skill)

    if jd_skills:
        skill_coverage = round(100.0 * len(matched_skills) / len(jd_skills), 1)
        skill_detection_note = f"{len(jd_skills)} explicit target skill(s) were detected in the job description."
    else:
        # A neutral floor prevents a non-technical JD from receiving an automatic zero while
        # clearly marking that no catalogued technical requirements were found.
        skill_coverage = 50.0
        skill_detection_note = "No explicit catalogued technical skills were detected; the skill component is held at a neutral baseline."

    context_analysis = compute_context_analysis(jd_text, candidate_text)
    context_score = safe_float(context_analysis.get("score"))

    structure = compute_resume_structure_score(resume_result)
    section_score = safe_float(structure.get("score"))

    experience = compute_experience_relevance(candidate_text, matched_skills)
    experience_score = safe_float(experience.get("score"))

    score_contributions = {
        "Skill Coverage": round(skill_coverage * 0.55, 1),
        "Keyword Context": round(context_score * 0.20, 1),
        "Resume Structure": round(section_score * 0.10, 1),
        "Experience Evidence": round(experience_score * 0.15, 1),
    }
    ats_score = round(clamp(sum(score_contributions.values())), 1)

    priority_map = extract_priority_map(jd_text)
    critical_gaps: List[str] = []
    important_gaps: List[str] = []
    optional_gaps: List[str] = []
    for skill in missing_skills:
        level = priority_map.get(skill, "important")
        if level == "critical":
            critical_gaps.append(skill)
        elif level == "optional":
            optional_gaps.append(skill)
        else:
            important_gaps.append(skill)

    priority_recommendations = build_priority_recommendations(critical_gaps, important_gaps, optional_gaps)

    recommendations: List[str] = []
    if critical_gaps:
        recommendations.append(
            "Validate the critical gaps first: " + ", ".join(display_skill(skill) for skill in critical_gaps[:5]) + ". Learn or prove them before adding them to the resume."
        )
    elif important_gaps:
        recommendations.append(
            "Prioritize the most relevant missing skills: " + ", ".join(display_skill(skill) for skill in important_gaps[:5]) + "."
        )
    if matched_skills:
        recommendations.append(
            "Strengthen evidence for matched skills by linking them to outcomes: " + ", ".join(display_skill(skill) for skill in matched_skills[:5]) + "."
        )
    if context_score < 50:
        missing_terms = coerce_list(context_analysis.get("missing_terms"))[:6]
        if missing_terms:
            recommendations.append(
                "Mirror truthful target-role language in relevant bullets, especially: " + ", ".join(missing_terms) + "."
            )
        else:
            recommendations.append("Use more job-specific terminology in project and experience descriptions without copying the job post verbatim.")
    if experience_score < 60 and matched_skills:
        recommendations.append("Move key skills out of a standalone list and into achievement bullets that show what you built, improved, analyzed, or deployed.")
    recommendations.extend(_failed_structure_recommendations(structure.get("checks", [])))
    recommendations = list(dict.fromkeys(recommendations))[:8]

    target_title = guess_target_title(jd_text)
    result: Dict[str, Any] = {
        # Original compatible keys
        "ats_score": ats_score,
        "skill_coverage": skill_coverage,
        "uniqueness_score": round(context_score, 1),
        "section_score": round(section_score, 1),
        "experience_score": round(experience_score, 1),
        "matched_skills": matched_skills,
        "missing_skills": missing_skills,
        "critical_gaps": critical_gaps,
        "important_gaps": important_gaps,
        "optional_gaps": optional_gaps,
        "priority_recommendations": priority_recommendations,
        "jd_skill_count": len(jd_skills),
        "recommendations": recommendations,
        "target_title": target_title,
        # Added explainability and UI/PDF intelligence
        "score_contributions": score_contributions,
        "matched_context_terms": context_analysis.get("matched_terms", []),
        "missing_context_terms": context_analysis.get("missing_terms", []),
        "context_term_count": context_analysis.get("term_count", 0),
        "structure_checks": structure.get("checks", []),
        "section_presence": structure.get("sections", {}),
        "contact_checks": structure.get("contact_checks", {}),
        "resume_word_count": structure.get("word_count", 0),
        "resume_action_verb_count": structure.get("action_verb_count", 0),
        "resume_metric_count": structure.get("metric_count", 0),
        "evidence_map": experience.get("evidence", []),
        "evidence_skills": experience.get("evidence_skills", []),
        "unsupported_skills": experience.get("unsupported_skills", []),
        "skill_detection_note": skill_detection_note,
        "target_summary": summarize_target_job(jd_text, target_title, sorted(jd_skills, key=display_skill)),
    }
    result["fit_summary"] = build_fit_summary(result)
    return result


