def score_status(score: float) -> Tuple[str, str]:
    value = clamp(safe_float(score))
    if value >= 80:
        return "Strong Match", COLOR_TEAL
    if value >= 65:
        return "Competitive", COLOR_CYAN
    if value >= 50:
        return "Needs Improvement", COLOR_AMBER
    return "Weak Match", COLOR_RUST


def score_explanation(score: float, matched_count: int, missing_count: int) -> str:
    label, _ = score_status(score)
    if label == "Strong Match":
        return "Your resume aligns closely with the target role. Focus on sharpening evidence and tailoring the strongest achievements."
    if label == "Competitive":
        return f"Your resume covers much of the role, but {missing_count} target skill gap(s) or evidence gaps still limit the match."
    if label == "Needs Improvement":
        return f"The resume shows {matched_count} direct skill match(es), but several requirements and target-role terms need stronger evidence."
    return "The resume currently demonstrates limited alignment with this target role. Address critical requirements before applying."


