def save_uploaded_file(uploaded_file: Any) -> str:
    """Save an uploaded resume safely regardless of current file cursor position."""
    suffix = os.path.splitext(str(uploaded_file.name))[1].lower()

    try:
        uploaded_file.seek(0)
    except Exception:
        pass

    try:
        payload = uploaded_file.getvalue()
    except Exception:
        payload = uploaded_file.getbuffer().tobytes()

    if not payload:
        raise ValueError("Uploaded resume is empty.")

    with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as temp_file:
        temp_file.write(payload)
        temp_file.flush()
        return temp_file.name


def validate_uploaded_resume(uploaded_file: Any) -> Optional[str]:
    if uploaded_file is None:
        return "Choose a PDF or DOCX resume first."

    suffix = os.path.splitext(str(uploaded_file.name))[1].lower()

    if suffix not in {".pdf", ".docx"}:
        return "Unsupported file type. Upload a PDF or DOCX resume."

    size = getattr(uploaded_file, "size", None)

    if size is not None and size > MAX_UPLOAD_MB * 1024 * 1024:
        return f"This file is larger than {MAX_UPLOAD_MB} MB. Upload a smaller resume file."

    return None


def analyze_uploaded_resume(uploaded_file: Any) -> Tuple[Optional[Dict[str, Any]], Optional[str]]:
    validation_error = validate_uploaded_resume(uploaded_file)

    if validation_error:
        return None, validation_error

    temp_path: Optional[str] = None

    try:
        try:
            uploaded_file.seek(0)
        except Exception:
            pass

        temp_path = save_uploaded_file(uploaded_file)

        result = analyze_resume(temp_path)

        if not isinstance(result, Mapping):
            return None, (
                "Resume analyzer returned unexpected result type: "
                f"{type(result).__name__}. Expected dictionary."
            )

        result_dict = dict(result)

        extracted_text = get_resume_text(result_dict).strip()
        detected_skills = get_detected_skills(result_dict)

        if not extracted_text and not detected_skills:
            returned_keys = ", ".join(str(k) for k in result_dict.keys()) or "none"

            return None, (
                "No readable resume text or skills were extracted. "
                "The PDF may be scanned/image-only, locked, corrupt, "
                "or the extractor returned unexpected fields. "
                f"Returned keys: {returned_keys[:300]}"
            )

        return result_dict, None

    except Exception as exc:
        return None, f"{type(exc).__name__}: {exc}"

    finally:
        if temp_path and os.path.exists(temp_path):
            try:
                os.remove(temp_path)
            except OSError:
                pass


def call_llama_api(messages: Sequence[Mapping[str, str]]) -> Tuple[Optional[str], Optional[str]]:
    """Call the existing OpenAI-compatible local Llama endpoint without changing its contract."""
    try:
        response = requests.post(
            API_URL,
            json={"messages": list(messages), "temperature": 0.7, "max_tokens": 700},
            timeout=(10, 120),
        )
        response.raise_for_status()
        data = response.json()
        choices = data.get("choices") if isinstance(data, Mapping) else None
        if not choices or not isinstance(choices, Sequence):
            return None, "The local Llama server responded, but its response format was incomplete."
        message = choices[0].get("message", {}) if isinstance(choices[0], Mapping) else {}
        answer = message.get("content") if isinstance(message, Mapping) else None
        if not answer:
            return None, "The local Llama server returned an empty response. Please try again."
        return str(answer), None
    except requests.exceptions.ConnectionError:
        return None, "Could not connect to the local Llama server. Make sure llama-server is running on port 8080."
    except requests.exceptions.Timeout:
        return None, "The mentor request timed out. Try again with a shorter question or confirm the local model is responsive."
    except requests.exceptions.HTTPError as exc:
        status = exc.response.status_code if exc.response is not None else "unknown"
        return None, f"The local Llama server returned HTTP {status}. Check the server console and API compatibility."
    except ValueError:
        return None, "The local Llama server did not return valid JSON. Check the OpenAI-compatible endpoint configuration."
    except Exception:
        return None, "The AI mentor is temporarily unavailable. Please try again after checking the local server."


def build_mentor_context() -> Optional[str]:
    result = st.session_state.get("analysis_result")
    if not result:
        return None

    predicted = get_predicted_career(result)
    confidence = get_confidence_percent(result)
    skills = get_detected_skills(result)
    resume_text = truncate_text(get_resume_text(result), MENTOR_RESUME_CONTEXT_CHARS)

    context_lines = [
        "CANDIDATE ANALYSIS CONTEXT",
        f"Predicted career: {predicted}",
        f"Prediction confidence: {confidence:.1f}%" if confidence is not None else "Prediction confidence: unavailable",
        "Detected skills: " + (", ".join(skills) if skills else "none extracted"),
    ]

    jd_result = st.session_state.get("jd_analysis_result")
    if jd_result:
        context_lines.extend(
            [
                f"Target role: {jd_result.get('target_title') or 'not detected'}",
                f"ATS score: {safe_float(jd_result.get('ats_score')):.1f}%",
                "Matched skills: " + ", ".join(display_skill(skill) for skill in jd_result.get("matched_skills", [])),
                "Missing skills: " + ", ".join(display_skill(skill) for skill in jd_result.get("missing_skills", [])),
                "Critical gaps: " + ", ".join(display_skill(skill) for skill in jd_result.get("critical_gaps", [])),
                "Important gaps: " + ", ".join(display_skill(skill) for skill in jd_result.get("important_gaps", [])),
                f"Fit summary: {jd_result.get('fit_summary', '')}",
            ]
        )

    if resume_text:
        context_lines.extend(["", "RESUME TEXT (TRUNCATED)", resume_text])

    jd_text = truncate_text(st.session_state.get("job_description", ""), MENTOR_JD_CONTEXT_CHARS)
    if jd_text:
        context_lines.extend(["", "TARGET JOB DESCRIPTION (TRUNCATED)", jd_text])

    context_lines.extend(
        [
            "",
            "Use only supported evidence from this context. Do not invent experience, metrics, or credentials.",
        ]
    )
    return "\n".join(context_lines)


def build_api_messages() -> List[Dict[str, str]]:
    api_messages: List[Dict[str, str]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    context = build_mentor_context()
    if context:
        api_messages.append({"role": "system", "content": context})
    for message in st.session_state.get("messages", []):
        if not isinstance(message, Mapping):
            continue
        role = str(message.get("role", "user"))
        content = str(message.get("content", ""))
        if role in {"user", "assistant", "system"} and content:
            api_messages.append({"role": role, "content": content})
    return api_messages


