def _pdf_cache_key(result: Mapping[str, Any], jd_result: Mapping[str, Any]) -> str:
    parts = [
        str(st.session_state.get("analyzed_file_signature") or st.session_state.get("analyzed_filename") or "resume"),
        str(st.session_state.get("matched_jd_signature") or "job"),
        str(jd_result.get("ats_score", "0")),
        get_predicted_career(result),
    ]
    return hashlib.sha256("|".join(parts).encode("utf-8", errors="ignore")).hexdigest()


